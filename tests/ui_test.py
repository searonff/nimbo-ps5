import time, json, urllib.request
from playwright.sync_api import sync_playwright
B = "http://127.0.0.1:8090/"
S = "/home/claude/test/shots/"
errors = []
fails = []
def check(n, c, info=""):
    print(("OK   " if c else "FAIL ") + n + ("" if c else f" -> {info}"), flush=True)
    if not c: fails.append(n)
def api(m, p, b=None):
    r = urllib.request.Request("http://127.0.0.1:8090" + p, data=json.dumps(b).encode() if b is not None else None, method=m, headers={"Content-Type": "application/json"})
    return json.loads(urllib.request.urlopen(r).read() or b"{}")
