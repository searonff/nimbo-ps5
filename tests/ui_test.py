    br = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg = br.new_page(viewport={"width": 1920, "height": 1080})
    pg.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
